const tables: Record<SupportedLocale, GroceryTable> = { en, pt, fr, es };

export function groceryT(locale: SupportedLocale, key: string): string | undefined {
  const table = tables[locale] ?? tables.en;
  if (key in table) return table[key as GroceryTranslationKey];
  if (key in tables.en) return tables.en[key as GroceryTranslationKey];
  return undefined;
}
